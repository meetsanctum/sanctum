import { assertKnownMigrations } from "@meetsanctum/app-sdk/storage";
import Database from "better-sqlite3";
import {
  drizzle,
  type BetterSQLite3Database,
} from "drizzle-orm/better-sqlite3";
import { migrate } from "drizzle-orm/better-sqlite3/migrator";
import { mkdirSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

// The core's own database: one SQLite file in its data volume for People,
// Auth and the core's other modules. Apps keep their own files. The manager
// copies the whole volume before an update, with the core stopped, and puts
// it back if the update rolls back.

export const coreDatabaseFile = "core.db";

// Generated by drizzle-kit from each module's schema.ts (drizzle.config.ts).
export const migrationsFolder = fileURLToPath(
  new URL("../migrations", import.meta.url),
);

// With its connection, which says whether a transaction is open.
export type CoreDatabase = BetterSQLite3Database & {
  $client: Database.Database;
};

export type OpenCoreDatabase = {
  db: CoreDatabase;
  // Checkpoints the write-ahead log, so the file is whole on its own.
  close: () => void;
};

/**
 * Runs `work` in one transaction that's on the disk once it returns. SQLite as it's
 * set up here can lose its last commits in a power cut, which is fine for almost
 * everything and not for what an update's commit rests on.
 */
export function durably<T>(db: CoreDatabase, work: () => T): T {
  const sqlite = db.$client;
  const before = sqlite.pragma("synchronous", { simple: true }) as number;
  sqlite.pragma("synchronous = FULL");
  try {
    return db.transaction(work);
  } finally {
    sqlite.pragma(`synchronous = ${before}`);
  }
}

// Opens the database, migrating it to this build's schema.
export function openCoreDatabase(
  dataDir: string,
  options: { migrationsFolder?: string } = {},
): OpenCoreDatabase {
  mkdirSync(dataDir, { recursive: true });
  const sqlite = new Database(join(dataDir, coreDatabaseFile));
  try {
    sqlite.pragma("journal_mode = WAL");
    sqlite.pragma("foreign_keys = ON");
    const folder = options.migrationsFolder ?? migrationsFolder;
    assertKnownMigrations(sqlite, folder);
    const db = drizzle({ client: sqlite });
    migrate(db, { migrationsFolder: folder });
    return { db, close: () => sqlite.close() };
  } catch (error) {
    sqlite.close();
    throw error;
  }
}
